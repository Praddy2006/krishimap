const express = require('express');
const pool = require('../config/db');
const requireAuth = require('./requireAuth');
const PDFDocument = require('pdfkit');

const router = express.Router();

// GET /api/states — list all states with data (for a dropdown/search fallback)
router.get('/', requireAuth, async (req, res) => {
  try {
    const [rows] = await pool.query('SELECT name FROM states ORDER BY name');
    res.json(rows);
  } catch (err) {
    console.error('States list error:', err);
    res.status(500).json({ error: 'Could not fetch state list.' });
  }
});

// ---- Shared PDF helpers ----
function writeHeader(doc, title) {
  doc.fontSize(22).fillColor('#15171a').text(title, { align: 'left' });
  doc.moveDown(0.2);
  doc.fontSize(10).fillColor('#6b7075').text(`Generated on ${new Date().toLocaleString('en-IN')}`);
  doc.moveDown(1);
}

function writeStateSection(doc, state) {
  doc.fontSize(20).fillColor('#f6851b').text(state.name);
  doc.moveDown(0.5);

  function field(label, value) {
    doc.fontSize(9).fillColor('#6b7075').text(label.toUpperCase(), { characterSpacing: 0.5 });
    doc.moveDown(0.1);
    doc.fontSize(12).fillColor('#15171a').text(value || 'Not available');
    doc.moveDown(0.6);
  }

  field('Soil Type', state.soil_type);
  field('Major Crops', state.major_crops);
  field('Climate', state.climate);
  field('Farming Notes', state.farming_notes);
  doc.moveDown(0.5);
}

function writeFooter(doc) {
  doc.moveDown(1);
  doc.fontSize(9).fillColor('#9fb3a4')
    .text('Generated by KrishiMap — a state-wise soil and crop information system for India.');
}

// GET /api/states/report/all — PDF covering every state in the database
router.get('/report/all', requireAuth, async (req, res) => {
  try {
    const [rows] = await pool.query('SELECT * FROM states ORDER BY name');

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', 'attachment; filename="KrishiMap_All_States_Report.pdf"');

    const doc = new PDFDocument({ margin: 50 });
    doc.pipe(res);

    writeHeader(doc, 'KrishiMap — All States Soil Report');
    doc.fontSize(10).fillColor('#6b7075').text(`${rows.length} states included`);
    doc.moveDown(1);

    rows.forEach((state, i) => {
      if (i > 0) doc.addPage();
      writeStateSection(doc, state);
    });

    writeFooter(doc);
    doc.end();
  } catch (err) {
    console.error('All-states report error:', err);
    res.status(500).json({ error: 'Could not generate the report.' });
  }
});

// GET /api/states/report/visited — PDF covering only states this user has clicked
router.get('/report/visited', requireAuth, async (req, res) => {
  try {
    const [rows] = await pool.query(
      `SELECT s.*, v.visit_count, v.first_visited_at, v.last_visited_at
       FROM visited_states v
       JOIN states s ON s.name = v.state_name
       WHERE v.user_id = ?
       ORDER BY v.last_visited_at DESC`,
      [req.session.userId]
    );

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', 'attachment; filename="My_Visited_States_Report.pdf"');

    const doc = new PDFDocument({ margin: 50 });
    doc.pipe(res);

    writeHeader(doc, `KrishiMap — ${req.session.userName}'s Visited States`);

    if (rows.length === 0) {
      doc.fontSize(12).fillColor('#15171a')
        .text('You have not explored any states yet. Click on a state on the map to add it here.');
      writeFooter(doc);
      doc.end();
      return;
    }

    doc.fontSize(10).fillColor('#6b7075').text(`${rows.length} state(s) visited`);
    doc.moveDown(1);

    rows.forEach((state, i) => {
      if (i > 0) doc.addPage();
      writeStateSection(doc, state);
      doc.fontSize(9).fillColor('#9fb3a4')
        .text(`Visited ${state.visit_count} time(s) — last on ${new Date(state.last_visited_at).toLocaleString('en-IN')}`);
      doc.moveDown(0.5);
    });

    writeFooter(doc);
    doc.end();
  } catch (err) {
    console.error('Visited-states report error:', err);
    res.status(500).json({ error: 'Could not generate the report.' });
  }
});

// POST /api/states/:name/visit — records that this user viewed this state
router.post('/:name/visit', requireAuth, async (req, res) => {
  try {
    const { name } = req.params;
    await pool.query(
      `INSERT INTO visited_states (user_id, state_name)
       VALUES (?, ?)
       ON DUPLICATE KEY UPDATE visit_count = visit_count + 1, last_visited_at = NOW()`,
      [req.session.userId, name]
    );
    res.json({ message: 'Visit recorded.' });
  } catch (err) {
    console.error('Visit tracking error:', err);
    res.status(500).json({ error: 'Could not record visit.' });
  }
});

// GET /api/states/:name/report — single-state PDF
router.get('/:name/report', requireAuth, async (req, res) => {
  try {
    const { name } = req.params;
    const [rows] = await pool.query('SELECT * FROM states WHERE name = ?', [name]);

    if (rows.length === 0) {
      return res.status(404).json({ error: `No data yet for "${name}".` });
    }

    const state = rows[0];
    const fileSafeName = state.name.replace(/\s+/g, '_');

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${fileSafeName}_soil_report.pdf"`);

    const doc = new PDFDocument({ margin: 50 });
    doc.pipe(res);

    writeHeader(doc, 'KrishiMap Soil Report');
    writeStateSection(doc, state);
    writeFooter(doc);

    doc.end();
  } catch (err) {
    console.error('PDF report error:', err);
    res.status(500).json({ error: 'Could not generate the report.' });
  }
});

// GET /api/states/:name — soil/crop/climate report for one state (JSON)
router.get('/:name', requireAuth, async (req, res) => {
  try {
    const { name } = req.params;
    const [rows] = await pool.query('SELECT * FROM states WHERE name = ?', [name]);

    if (rows.length === 0) {
      return res.status(404).json({
        error: `No data yet for "${name}". Add a row to the states table to fill this in.`
      });
    }

    res.json(rows[0]);
  } catch (err) {
    console.error('State lookup error:', err);
    res.status(500).json({ error: 'Could not fetch state data.' });
  }
});

module.exports = router;